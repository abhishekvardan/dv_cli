/**
 * Walking a project directory for deployment.
 *
 * Two things make this more than a `readdir` loop:
 *
 *  - **What to leave out.** Uploading `node_modules` is both enormous and pointless —
 *    the platform installs dependencies itself. Getting the ignore list wrong is the
 *    difference between a 300 KB upload and a 300 MB one.
 *  - **Hashing.** Vercel's upload API is content-addressed by SHA1: you upload a file
 *    once, then reference it by digest. Files it already holds are skipped entirely,
 *    which is what makes a redeploy of a mostly-unchanged tree fast.
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/**
 * Never uploaded, regardless of ignore files.
 *
 * `node_modules` and build output are reinstalled or regenerated by the platform.
 * `.git` and `.env` are the two that matter for safety: one is large and private, the
 * other is credentials, and neither belongs in a deployment payload.
 */
const ALWAYS_SKIP = new Set([
  'node_modules',
  '.git',
  '.vercel',
  '.next',
  '.nuxt',
  '.svelte-kit',
  '.turbo',
  '.cache',
  'dist',
  'build',
  'out',
  'coverage',
  '.DS_Store',
]);

/** Files never uploaded even when they sit in an otherwise included folder. */
const SKIP_FILE = [/^\.env($|\.)/, /\.log$/, /^npm-debug\.log/, /\.tsbuildinfo$/];

export interface WalkedFile {
  /** Path relative to the root, always forward-slashed — the API expects POSIX. */
  file: string;
  absolute: string;
  size: number;
  sha: string;
}

export interface WalkOptions {
  /** Refuse anything larger; the platform rejects oversized files anyway. */
  maxFileBytes?: number;
  /** Extra ignore patterns, e.g. from .vercelignore. */
  ignore?: string[];
}

/**
 * Match an ignore pattern.
 *
 * Deliberately a small subset of glob — leading slash, trailing slash, and `*` — rather
 * than a full implementation. It covers what ignore files actually contain, and a
 * half-correct full glob would be worse than an obviously limited one.
 */
function matches(pattern: string, path: string): boolean {
  const clean = pattern.replace(/^\/+/, '').replace(/\/+$/, '');
  if (!clean) return false;
  if (clean.includes('*')) {
    const re = new RegExp(
      `^${clean.split('*').map((p) => p.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*')}$`,
    );
    return path.split('/').some((segment) => re.test(segment)) || re.test(path);
  }
  return path === clean || path.startsWith(`${clean}/`) || path.split('/').includes(clean);
}

/** Read ignore patterns from a file, if it exists. */
export function readIgnoreFile(root: string, name: string): string[] {
  const path = join(root, name);
  if (!existsSync(path)) return [];
  return readFileSync(path, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    // Negations are not supported; silently honouring the positive half of a `!rule`
    // would exclude something the user explicitly asked to include.
    .filter((l) => l && !l.startsWith('#') && !l.startsWith('!'));
}

/**
 * Every file that should be uploaded, hashed and ready to reference.
 *
 * Reads each file once: the same buffer is hashed and its length taken, so a large
 * tree is not walked twice.
 */
export function walkProject(root: string, options: WalkOptions = {}): WalkedFile[] {
  const maxBytes = options.maxFileBytes ?? 100 * 1024 * 1024;
  const ignore = options.ignore ?? [];
  const found: WalkedFile[] = [];

  const visit = (dir: string) => {
    let entries: string[];
    try {
      entries = readdirSync(dir);
    } catch {
      // An unreadable directory should not abort the whole deployment.
      return;
    }

    for (const name of entries) {
      if (ALWAYS_SKIP.has(name)) continue;

      const absolute = join(dir, name);
      const rel = relative(root, absolute).split(sep).join('/');
      if (ignore.some((pattern) => matches(pattern, rel))) continue;

      let info;
      try {
        info = statSync(absolute);
      } catch {
        continue;
      }

      if (info.isDirectory()) {
        visit(absolute);
        continue;
      }
      if (!info.isFile()) continue;
      if (SKIP_FILE.some((re) => re.test(name))) continue;
      if (info.size > maxBytes) continue;

      const body = readFileSync(absolute);
      found.push({
        file: rel,
        absolute,
        size: body.length,
        // SHA1 is not a security choice here — it is the digest Vercel's upload API
        // addresses content by.
        sha: createHash('sha1').update(body).digest('hex'),
      });
    }
  };

  visit(root);
  return found.sort((a, b) => a.file.localeCompare(b.file));
}

/** Human-readable byte size. */
export function humanSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} kB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
